package hnsw

import (
	"container/heap"
)

type Item struct {
	ID       uint64
	Distance float32
}

// MinHeap orders items by lowest distance first.
type MinHeap []Item

func (h MinHeap) Len() int           { return len(h) }
func (h MinHeap) Less(i, j int) bool { return h[i].Distance < h[j].Distance }
func (h MinHeap) Swap(i, j int)      { h[i], h[j] = h[j], h[i] }

func (h *MinHeap) Push(x any) {
	*h = append(*h, x.(Item))
}

func (h *MinHeap) Pop() any {
	old := *h
	n := len(old)
	item := old[n-1]
	*h = old[0 : n-1]
	return item
}

// MaxHeap orders items by highest distance first.
type MaxHeap []Item

func (h MaxHeap) Len() int           { return len(h) }
func (h MaxHeap) Less(i, j int) bool { return h[i].Distance > h[j].Distance }
func (h MaxHeap) Swap(i, j int)      { h[i], h[j] = h[j], h[i] }

func (h *MaxHeap) Push(x any) {
	*h = append(*h, x.(Item))
}

func (h *MaxHeap) Pop() any {
	old := *h
	n := len(old)
	item := old[n-1]
	*h = old[0 : n-1]
	return item
}

func (h MaxHeap) Peek() Item {
	return h[0]
}

func (h MinHeap) Peek() Item {
	return h[0]
}

// Ensure heap interface implementations
var _ heap.Interface = (*MinHeap)(nil)
var _ heap.Interface = (*MaxHeap)(nil)
